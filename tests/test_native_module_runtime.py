    def test_composer_transition_exception_rejects_untrusted_metadata(self):
        command, overrides, target = self.mount_fixture()
        for invalid in ('mode', 'target-mode', 'set-id', 'label', 'payload-label', 'owner', 'bytes', 'catalog'):
            with self.subTest(invalid=invalid):
                before = self.mount_payload.read_bytes()
                labels = self.environment['HYPEROS_NATIVE_TEST_LABELS']
                owner = self.environment['HYPEROS_NATIVE_TEST_OWNER']
                catalog = (self.module / 'targets.tsv').read_text()
                if invalid == 'mode': self.mount_payload.chmod(0o644)
                elif invalid == 'target-mode': self.target.chmod(0o644)
                elif invalid == 'set-id': self.mount_payload.chmod(0o4755)
                elif invalid == 'label':
                    self.environment['HYPEROS_NATIVE_TEST_LABELS'] = json.dumps({target: 'u:object_r:system_file:s0'})
                elif invalid == 'payload-label':
                    self.environment['HYPEROS_NATIVE_TEST_LABELS'] = json.dumps({target: 'u:object_r:hal_graphics_composer_default_exec:s0'})
                elif invalid == 'owner': self.environment['HYPEROS_NATIVE_TEST_OWNER'] = '1000:1000'
                elif invalid == 'bytes': self.mount_payload.write_bytes(b'unknown native')
                elif invalid == 'catalog': (self.module / 'targets.tsv').write_text('')
                result = self.shell(command, overrides=overrides, check=False)
                self.assertNotEqual(result.returncode, 0)
                self.assertFalse(self.mount_trace.exists())
                self.assertEqual((self.proc / '1/mountinfo').read_text(), '')
                self.mount_payload.write_bytes(before); self.mount_payload.chmod(0o755); self.target.chmod(0o755)
                self.environment['HYPEROS_NATIVE_TEST_LABELS'] = labels
                self.environment['HYPEROS_NATIVE_TEST_OWNER'] = owner
                (self.module / 'targets.tsv').write_text(catalog)

