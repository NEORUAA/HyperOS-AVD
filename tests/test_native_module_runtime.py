def digest(data):
    return hashlib.sha256(data).hexdigest()


BUSYBOX = r'''#!/usr/bin/env python3
import fcntl, hashlib, json, os, pathlib, stat, subprocess, sys
args = sys.argv[1:]
command, args = args[0], args[1:]
metadata = json.loads(pathlib.Path(os.environ['HYPEROS_NATIVE_TEST_METADATA']).read_text())
if command == 'nsenter':
    args = args[args.index('--') + 1:]
    files = json.loads(os.environ.get('HYPEROS_NATIVE_TEST_FILES', '{}'))
    if args[0] == '/system/bin/ls':
        labels = json.loads(os.environ.get('HYPEROS_NATIVE_TEST_LABELS', '{}'))
        value = pathlib.Path(files.get(args[-1], args[-1])).stat()
        attrs = metadata.get(f'{value.st_dev}:{value.st_ino}', {})
        print(attrs.get('context', labels.get(args[-1], 'u:object_r:system_lib_file:s0')) + ' ' + args[-1]); sys.exit(0)
    args = [files.get(value, value) for value in args]
    os.execvp(args[0], args)
if command == 'sha256sum':
    if args and args[0] == '-c':
        for line in pathlib.Path(args[1]).read_text().splitlines():
            expected, name = line.split(None, 1)
            if hashlib.sha256(pathlib.Path(name.strip().lstrip('*')).read_bytes()).hexdigest() != expected:
                sys.exit(1)
        if os.environ.get('HYPEROS_NATIVE_TEST_TRACE'):
            with open(os.environ['HYPEROS_NATIVE_TEST_TRACE'], 'a') as output:
                output.write('assets-verified\n')
        sys.exit(0)
    try:
        for name in args:
            print(hashlib.sha256(pathlib.Path(name).read_bytes()).hexdigest() + '  ' + name)
    except OSError:
        sys.exit(1)
    sys.exit(0)
if command == 'stat' and args[0] == '-c':
    try:
        value = pathlib.Path(args[2]).stat()
        attrs = metadata.get(f'{value.st_dev}:{value.st_ino}', {})
        form = args[1]
        print(form.replace('%a', format(stat.S_IMODE(value.st_mode), 'o'))
              .replace('%s', str(value.st_size)).replace('%i', str(value.st_ino))
              .replace('%Y', str(int(value.st_mtime))).replace('%d', str(value.st_dev))
              .replace('%u:%g', attrs.get('owner', os.environ.get('HYPEROS_NATIVE_TEST_OWNER', f'{value.st_uid}:{value.st_gid}'))))
    except OSError:
        sys.exit(1)
    sys.exit(0)
if command == 'flock':
    try:
        fcntl.flock(int(args[-1]), fcntl.LOCK_EX | fcntl.LOCK_NB)
    except OSError:
        sys.exit(1)
    sys.exit(0)
os.execvp(command, [command] + args)
'''


