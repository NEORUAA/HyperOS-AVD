        self.assertNotIn('rear-display|' + str(self.target) + '|pending|',
                         (self.module / 'state/status.tsv').read_text())
        self.target.write_bytes(self.original); trace.unlink()
        self.shell('native_reconcile early', overrides=overrides + self.rear_properties())
        self.assertEqual(self.target.read_bytes(), final)
        self.assertEqual(trace.read_text(), digest(self.after) + '\n' + digest(final) + '\n')
