    def test_pad_skips_rear_chain_while_phone_keeps_verified_back_panel(self):
        final = self.composer_chain()
        trace = self.root / 'feature-binds'
        overrides = self.safe_paths() + '\n'
        overrides += 'native_mount() { cp "$2" "$1"; printf "%s\\n" "$5" >> ' + shlex.quote(str(trace)) + '; }\n'
        self.shell('native_reconcile early', overrides=overrides)
